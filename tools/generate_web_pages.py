"""Generate deterministic gzip pages; --check detects stale checked-in assets."""
from pathlib import Path
import argparse
import gzip
import hashlib
import re

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
output = ['// Generated by tools/generate_web_pages.py. Do not edit.', '#pragma once', '']
for filename, symbol in [('ScalePage.h', 'PAGE'), ('SettingsPage.h', 'SETTINGS_PAGE')]:
    source = (root / filename).read_text()
    data = re.search(r'R"HTML\((.*?)\)HTML";', source, re.S)[1].encode('utf-8')
    packed = gzip.compress(data, compresslevel=9, mtime=0)
    assert gzip.decompress(packed) == data
    checksum = 2166136261
    for byte in data:
        checksum = ((checksum ^ byte) * 16777619) & 0xffffffff
    output.append(f'static_assert(webcache::sourceHash({symbol}, sizeof({symbol}) - 1) == 0x{checksum:08x}u, "Run python3 tools/generate_web_pages.py after editing {filename}");')
    for suffix, content in [('IDENTITY', data), ('GZIP', packed)]:
        digest = hashlib.sha256(content).hexdigest()[:24]
        output.append(f'const char {symbol}_{suffix}_ETAG[] = "\\"{digest}-{suffix.lower()}\\"";')
    output.append(f'const uint8_t {symbol}_GZIP[] PROGMEM = {{')
    for offset in range(0, len(packed), 16):
        output.append('  ' + ', '.join(f'0x{b:02x}' for b in packed[offset:offset+16]) + ',')
    output.extend(['};', ''])
    print(f'{filename}: {len(data)} -> {len(packed)} bytes ({100*(1-len(packed)/len(data)):.1f}% smaller)')
expected = '\n'.join(output) + '\n'
target = root / 'WebPages.generated.h'
if args.check:
    if not target.exists() or target.read_text() != expected:
        raise SystemExit('WebPages.generated.h is stale; run python3 tools/generate_web_pages.py')
else:
    target.write_text(expected)
